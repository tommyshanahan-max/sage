// Copy the wallet into crowdfundme, for the public demo at crowdfundme.app/wallet.
//
//   node scripts/wallet-demo-sync.mjs
//
// A COPY, NOT A SHARED FOLDER, because each service here builds from its own
// directory (see docker-compose.yml) and crowdfundme's image cannot reach into
// board/. The board is the source of truth: edit board/lib/wallet and
// board/public/wallet.html, then run this. Every copied file says so at the
// top, so nobody fixes a bug in the copy and loses it at the next sync.
//
// Only what the demo needs comes across — no passkeys (the demo confirms in
// test mode), no real provider, no keys.

import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const from = path.join(root, "board");
const to = path.join(root, "cfm");
const HEADER = "// GENERATED by scripts/wallet-demo-sync.mjs from board/lib/wallet — edit there, not here.\n";
const files = ["money.js", "ledger.js", "service.js", "routes.js", "pages.js", "demo.js", "providers/mock.js"];

for (const f of files) {
  const src = await readFile(path.join(from, "lib/wallet", f), "utf8");
  const out = path.join(to, "lib/wallet", f);
  await mkdir(path.dirname(out), { recursive: true });
  await writeFile(out, HEADER + src);
  console.log("copied", f);
}
const html = (await readFile(path.join(from, "public/wallet.html"), "utf8"))
  .replace("{{DEMO}}", "")
  .replace("<!doctype html>", "<!doctype html>\n<!-- GENERATED by scripts/wallet-demo-sync.mjs from board/public/wallet.html — edit there, not here. -->");
await writeFile(path.join(to, "public/wallet.html"), html);
console.log("copied wallet.html");
